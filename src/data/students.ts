export const STUDENTS_DATA: Student[] = RAW_STUDENT_ROWS.map((row) => {
  const spaceIdx = row.rawName.indexOf(' ');
  const noAbsen = row.rawName.slice(0, spaceIdx).trim();
  const nama = row.rawName.slice(spaceIdx + 1).trim();
  const schoolSlug = row.sekolah.includes('MUDITA') ? 'MUDITA' : 'SMKN1';
  const classSlug = row.kelas.replace(/\s+/g, '');
  return {
    id: `${schoolSlug}-${classSlug}-${noAbsen}`,
    sekolah: row.sekolah,
    kelas: row.kelas,
    noAbsen,
    nama,
    namaLengkapDisplay: row.rawName,
  };
});

